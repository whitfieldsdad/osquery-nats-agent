SELECT
    "path",
    "filename",
    directory,
    "type",
    inode,
    "uid",
    gid,
    mode,
    device,
    volume_serial,
    "size",
    block_size,
    mtime,
    atime,
    ctime,
    btime,
    hard_links,
    CASE WHEN symlink = 1 THEN 'true' ELSE 'false' END AS is_symlink,
    symlink_target_path,
    shortcut_target_path,
    shortcut_target_type,
    shortcut_target_location,
    shortcut_start_in,
    shortcut_run,
    shortcut_comment,
    attributes
FROM "file"
WHERE directory = '/usr/bin';