SELECT
    "path",
    store,
    store_id,
    store_location,
    username,
    common_name,
    subject2 AS "subject",
    issuer2 AS issuer,
    CASE WHEN ca = 1 THEN 1 ELSE 0 END AS is_ca_certificate,
    CASE WHEN self_signed = 1 THEN 1 ELSE 0 END AS is_self_signed,
    not_valid_before,
    not_valid_after,
    signing_algorithm,
    key_algorithm,
    key_strength,
    key_usage,
    subject_key_id,
    authority_key_id,
    "serial",
    sha1,
    "sid",
FROM certificates
ORDER BY "path", "common_name"
